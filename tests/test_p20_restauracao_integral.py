    def test_n9_chave_estrangeira_quebrada_entre_partes(self):
        fk = [{"name": "z_fk_a_pai", "ddl": "create table public.z_fk_a_pai (id bigint primary key);", "rows": "insert into public.z_fk_a_pai values (1);"},
              {"name": "z_fk_b_filho", "ddl": "create table public.z_fk_b_filho (id bigint primary key, pai_id bigint not null references public.z_fk_a_pai(id));",
               "rows": "insert into public.z_fk_b_filho values (1, 1);"}]
        for fill in range(0, 7):  # tabelas de enchimento até o pai ficar numa parte ANTERIOR à do filho
            extra = [{"name": f"z_fk_0_{i}", "ddl": f"create table public.z_fk_0_{i} (id int primary key);"} for i in range(fill)] + fk
            src, dst, ddl, elig, kvfile, code, w, out = self.run_chain("n9", 94, extra=extra, scenario="fk_entre_partes")
            if not w.get("fk_order_unsuitable"):
                break
        self.assertTrue(w["ok"], w)  # o backup em si é consistente POR TABELA
        self.assertLess(w["fk"]["part_pai"], w["fk"]["part_filho"])
        a = archive(kvfile, out)
        self.assertEqual(a.returncode, 0, a.stdout[-600:])
        fresh(dst, owner=APP)
        r = restore(out, dst, ddl)
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("inconsistencia_entre_tabelas z_fk_b_filho", r.stdout)

