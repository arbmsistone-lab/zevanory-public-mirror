"""P20 v2 — teste OFICIAL de aceitação: restauração INTEGRAL do backup cifrado em PostgreSQL isolado.

Cadeia real, sem atalhos (docs/p20/particoes-v2.md, seção "Critério de aceite"):
  origem (esquema real: db/migrations + runtime_ddl() + dynamic_ddl(), mais tabelas sintéticas para chegar a E)
  -> backup pelo CÓDIGO REAL do Worker (worker/data-backup.mjs: plano autenticado, partes dinâmicas, AES-256-GCM com chave
     sintética gerada nesta execução e nunca gravada no repositório)
  -> arquivamento REAL (scripts/ops/backup_preserve_archive.py archive, lendo o KV gravado pelo Worker)
  -> restauração REAL (scripts/ops/restore_new_database.py rehearse) num banco NOVO do mesmo cluster descartável, pelo
     papel da aplicação (p20_app, não superusuário)
  -> comparação origem x destino, tabela por tabela: conjunto de tabelas = elegíveis do plano (credenciais ausentes),
     contagem de linhas, hash de linhas (row_hash_sql), colunas (nome, tipo, nulidade, padrão) e permissões do papel
     da aplicação (has_table_privilege SELECT/INSERT/UPDATE). O restaurador só diz "completo" com tudo isso verdadeiro.
Casos positivos: E = 88, 94, 121 e 180 elegíveis (3, 4, 5 e 6 partes). Contraprovas (cada uma tem de REPROVAR, sem
nada marcado como completo): esquema alterado entre o plano e uma parte; parte ausente; parte extra; relatório com HMAC
adulterado; bundle movido de parte; bundle corrompido; arquivamento sem a chave (nao_autenticado, restauração recusada);
chave estrangeira quebrada por escrita entre partes (inconsistencia_entre_tabelas). Também: escrita concorrente entre a
estatística e a exportação (linhas contadas no conteúdo copiado) e a compatibilidade do legado v1 cifrado de 3 partes
(o defeito crítico: antes o restaurador não decifrava; agora restaura, marcado legado_nao_autenticado).
Requer PG* de um servidor DESCARTÁVEL (o CI usa o serviço postgres:16 do job); sem PGHOST, pula. Nada aqui toca produção.
"""
