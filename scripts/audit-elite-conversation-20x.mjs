import {evaluateConversationQuality} from '../src/conversationQuality.mjs';
import {AGENT_SYSTEM_POLICY} from '../src/agentPolicy.mjs';

const checks=[];const add=(name,pass)=>checks.push([name,Boolean(pass)]);
const q=(message,extra={})=>evaluateConversationQuality({message,channel:'whatsapp',recentMessages:[],decision:{confidence:.9},...extra});
add('natural concise message',q('Entendi sua dúvida. Posso te mostrar o que está incluído e você decide com calma.').pass);
add('robotic opening blocked',!q('Prezado cliente, venho por meio desta responder sua solicitação.').pass);
add('fake urgency blocked',!q('Última chance! Você vai perder agora!').pass);
add('guaranteed result blocked',!q('Resultado 100% garantido e sem risco.').pass);
add('excessive uppercase blocked',!q('ATENÇÃO VOCÊ PRECISA DECIDIR AGORA SOBRE ESSA OFERTA').pass);
add('question overload blocked',!q('Qual a dúvida? Qual orçamento? Quando começa?').pass);
add('empty-value greeting blocked',!q('Olá!').pass);
add('low confidence blocked',!q('Posso te orientar sobre isso.',{decision:{confidence:.2}}).pass);
add('short useful answer allowed',q('Sim. Posso explicar os detalhes agora.').pass);
add('channel recorded',q('Posso te ajudar com esse ponto agora.').channel==='whatsapp');
const repeated='Posso explicar o que está incluído e você decide com calma.';
add('recent repetition blocked',!q(repeated,{recentMessages:[repeated]}).pass);
add('context-aware alternative allowed',q('Sobre o preço: primeiro vale comparar o que está incluído em cada opção.',{recentMessages:[repeated]}).pass);
add('policy uses supplied facts',/Use only supplied facts/i.test(AGENT_SYSTEM_POLICY));
add('policy requires natural pt-BR',/natural Brazilian Portuguese/i.test(AGENT_SYSTEM_POLICY));
add('policy requires continuity',/recent_conversation/i.test(AGENT_SYSTEM_POLICY)&&/lead_memory/i.test(AGENT_SYSTEM_POLICY));
add('policy covers objections',/For objections/i.test(AGENT_SYSTEM_POLICY));
add('policy forbids manipulation',/fake urgency/i.test(AGENT_SYSTEM_POLICY));
add('policy limits questions',/at most two questions/i.test(AGENT_SYSTEM_POLICY));
add('policy adapts WhatsApp',/For WhatsApp/i.test(AGENT_SYSTEM_POLICY));
add('policy preserves commercial gates',/Commercial and financial actions require/i.test(AGENT_SYSTEM_POLICY));
for(const [i,[name,pass]] of checks.entries())console.log(`${pass?'APPROVED':'FAILED'} ${String(i+1).padStart(2,'0')} ${name}`);
const failed=checks.filter(([,p])=>!p);
if(checks.length!==20||failed.length)process.exitCode=1;else console.log(`AUDIT_ELITE_CONVERSATION_20X_APPROVED units=${checks.length} approved=${checks.length} failed=0`);
