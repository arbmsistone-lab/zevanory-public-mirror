import { readFile, access } from 'node:fs/promises';
const root=new URL('../',import.meta.url);
const text=(p)=>readFile(new URL(p,root),'utf8');
const exists=async(p)=>{try{await access(new URL(p,root));return true}catch{return false}};
const checks=[]; const add=(name,ok)=>checks.push({name,ok:Boolean(ok)});
const market=await text('src/marketParameters.mjs');
const pipeline=await text('src/salesPipeline.mjs');
const economics=await text('src/unitEconomics.mjs');
const learning=await text('src/learningEngine.mjs');
const migration=await text('db/migrations/006_sales_machine.sql');
const schema=await text('src/schemaHealth.mjs');
const status=await text('src/operationalStatus.mjs');
const env=await text('.env.example');
add('01 market parameters exist',await exists('specs/MARKET_PARAMETERS.md'));
add('02 speed-to-lead benchmark sourced',market.includes('benchmark_max_minutes: 60')&&market.includes('operating_target_minutes: 5'));
add('03 prospecting touchpoint ceiling sourced',market.includes('benchmark_touchpoints: 8'));
add('04 checkout abandonment benchmark sourced',market.includes('70.22'));
add('05 web vitals benchmark sourced',market.includes('lcp_ms: 2500')&&market.includes('inp_ms: 200')&&market.includes('cls: 0.1'));
add('06 CRM pipeline state machine',pipeline.includes("'qualified','offer_sent'")&&pipeline.includes("'checkout_started','paid'"));
add('07 follow-up scheduler',pipeline.includes('buildFollowUpPlan')&&pipeline.includes('touchpoint_limit'));
add('08 unit economics engine',economics.includes('contribution_margin_brl')&&economics.includes('cac_brl')&&economics.includes('roas'));
add('09 positive economics required',economics.includes('non_positive_contribution_margin'));
add('10 learning engine requires real evidence',learning.includes('no_paid_orders')&&learning.includes('baseline_only:true'));
add('11 CRM table migration',migration.includes('CREATE TABLE IF NOT EXISTS sales_leads'));
add('12 action queue migration',migration.includes('CREATE TABLE IF NOT EXISTS sales_actions'));
add('13 economics snapshot migration',migration.includes('CREATE TABLE IF NOT EXISTS unit_economics_snapshots'));
add('14 migration ledger',migration.includes("'006_sales_machine'"));
add('15 schema requires CRM tables',schema.includes("'sales_leads'")&&schema.includes("'sales_actions'")&&schema.includes("'unit_economics_snapshots'"));
add('16 status exposes machine readiness',status.includes("crm:'ready'")&&status.includes("outbound_execution:'blocked'"));
add('17 migration apply guarded',await exists('scripts/apply-migration-006.mjs')&&(await text('scripts/apply-migration-006.mjs')).includes('MIGRATION_APPLY_ALLOWED'));
add('18 sales machine tests',await exists('test/sales-machine.test.mjs'));
add('19 commercial kill switches off',!env.includes('SALE_GLOBALLY_ENABLED=true')&&!env.includes('CHECKOUT_ENABLED=true')&&!env.includes('WHATSAPP_SALES_ENABLED=true'));
add('20 no invented conversion target',market.includes('require_real_baseline_before_conversion_target: true'));
for(const c of checks) console.log(`${c.ok?'APPROVED':'FAILED'} ${c.name}`);
const failed=checks.filter(c=>!c.ok);
console.log(`AUDIT_SALES_MACHINE_20X_${failed.length?'BLOCKED':'APPROVED'} units=20 approved=${20-failed.length} failed=${failed.length}`);
if(failed.length) process.exit(1);
