import { readFile, access } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const root=new URL('../',import.meta.url);
const rootPath=fileURLToPath(root);
const text=(p)=>readFile(new URL(p,root),'utf8');
const exists=async(p)=>{try{await access(new URL(p,root));return true}catch{return false}};
const checks=[]; const add=(name,ok)=>checks.push({name,ok:Boolean(ok)});
const security=await text('src/security.mjs');
const events=await text('api/events-public.mjs');
const server=await text('src/server-v2.mjs');
const vercel=JSON.parse(await text('vercel.json'));
const index=await text('public/index.html'); const pilot=await text('public/piloto.html');
const env=await text('.env.example');
const audit=spawnSync('npm audit --omit=dev --audit-level=low --json',{cwd:rootPath,encoding:'utf8',shell:true});
const headers=Object.fromEntries(vercel.headers[0].headers.map(x=>[x.key,x.value]));
add('01 security core exists',await exists('src/security.mjs'));
add('02 security tests exist',await exists('test/security.test.mjs'));
add('03 npm dependencies zero known vulnerabilities',audit.status===0);
add('04 strict CSP no unsafe inline eval',headers['Content-Security-Policy']?.includes("script-src 'self'")&&!headers['Content-Security-Policy']?.includes('unsafe-inline')&&!headers['Content-Security-Policy']?.includes('unsafe-eval'));
add('05 no inline script style',!/<style[>\s]/i.test(index+pilot)&&!/<script>([\s\S]*?)<\/script>/i.test(index+pilot));
add('06 origin validation',security.includes('origin_not_allowed')&&security.includes('PUBLIC_BASE_URL'));
add('07 payload limit',security.includes('MAX_PUBLIC_EVENT_BYTES = 4096'));
add('08 telemetry rate limit',events.includes('>= 60')&&events.includes("error: 'rate_limited'"));
add('09 constant time operator auth',security.includes('timingSafeEqual')&&server.includes('safeBearerEqual'));
add('10 no public admin and example secrets empty',!(await exists('api/admin-migrate.mjs'))&&env.includes('OPERATOR_TOKEN=')&&!/OPERATOR_TOKEN=\S+/.test(env));
for(const c of checks) console.log(`${c.ok?'APPROVED':'FAILED'} ${c.name}`);
const failed=checks.filter(c=>!c.ok); console.log(`AUDIT_SECURITY_10X_${failed.length?'BLOCKED':'APPROVED'} units=10 approved=${10-failed.length} failed=${failed.length}`); if(failed.length) process.exit(1);
