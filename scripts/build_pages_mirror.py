#!/usr/bin/env python3
"""ZEVANORY | GitHub Pages copy of this repository = redirect layer only (site audit C-01/C-02, Sol 264).

Why: GitHub Pages builds this branch (gh-pages, repository root) with Jekyll ("pages build and deployment")
and serves it at https://arbmsistone-lab.github.io/zevanory-public-mirror/. The root tree is NOT a website:
it is the editable SOURCE of the sales site (scripts/build_sales_public.py reads <slug>/index.html and
writes sales-public/, served by the sales Worker at vendas.zevanory.api.br). Served raw, those sources
are a stale, half-broken second copy of the store (paths with the project prefix mixed with root paths,
old home, "Piloto" 404, sources without the closed-sales notice, contato@). Nobody consumes the Pages
copy (no workflow, script or page links to github.io).

What this generator writes (and nothing else):
  * _config.yml            Jekyll config: `exclude` lists EVERY top-level entry of the repository except
                           pages-mirror/, so Pages publishes nothing from the source tree.
  * pages-mirror/*.html    One stub per HTML page the source tree used to publish: noindex, canonical to
                           the official URL, meta refresh 0 s and a visible link (works without JS). The
                           official URL is the canonical the sales build itself declares in
                           sales-public/<slug>.html (single source of truth); everything else goes to
                           the catalogue. No prices, no offers, no stylesheet, no images.
  * pages-mirror/404.html  Pages' not-found page (status 404, noindex, link to the catalogue).
  * pages-mirror/robots.txt  Allow all (crawlers must reach the noindex/redirect to drop the old URLs),
                           no Sitemap line.

The source tree is untouched: the sales build ignores _config.yml and pages-mirror/ (it reads named
slugs only), and the central Worker (zevanory.api.br) serves the frozen public/ snapshot of commit 83620c6
rebuilt by .github/workflows/central-production-deploy.yml, never this tree. The list of files comes from
`git ls-files` so local and CI runs agree (untracked files are never published by Pages either).

Usage:  python3 scripts/build_pages_mirror.py           # (re)generate
        python3 scripts/build_pages_mirror.py --check   # CI: fail if the committed output is stale
No network, no secrets."""
from __future__ import annotations

import argparse
import html
import re
import subprocess
import sys
from pathlib import Path

sys.dont_write_bytecode = True

ROOT = Path(__file__).resolve().parents[1]
STUB_DIR = "pages-mirror"
SALES_DIR = ROOT / "sales-public"
SALES_ORIGIN = "https://vendas.zevanory.api.br"
CATALOGUE = SALES_ORIGIN + "/solucoes"
PAGES_BASE = "/zevanory-public-mirror"
# Directories whose HTML is never a public page (tooling, evidence, tests). They are excluded like the rest;
# no stub is generated for them, so their old Pages URLs answer the 404 page.
NO_STUB_TOP = {"docs", "evidence", "tests", "scripts", "worker", "ops", "sandbox", "compliance", "contracts",
               "db", "data", "assets", "brand", "sales-overlay", "node_modules"}
CANONICAL_RE = re.compile(r'<link rel="canonical" href="(https://vendas\.zevanory\.api\.br/[^"]*)"')
HEADER = "# GENERATED by scripts/build_pages_mirror.py. Do not edit by hand; run the script.\n"


def jekyll_skipped(name: str) -> bool:
    """Entries Jekyll never reads from the source (special leading characters, backups)."""
    return name[:1] in (".", "_", "#", "~") or name.endswith("~")


def tracked_files() -> list[str]:
    out = subprocess.run(["git", "-C", str(ROOT), "ls-files", "-z"], check=True, capture_output=True).stdout
    return sorted(f for f in out.decode("utf-8").split("\0") if f)


def top_level_entries(files: list[str]) -> list[str]:
    return sorted({f.split("/", 1)[0] for f in files} - {STUB_DIR, "_config.yml"} - {n for n in {f.split("/", 1)[0] for f in files} if jekyll_skipped(n)})


def sales_canonicals() -> dict[str, str]:
    out = {}
    for page in sorted(SALES_DIR.glob("*.html")):
        m = CANONICAL_RE.search(page.read_text(encoding="utf-8"))
        if m:
            out[page.stem] = m.group(1)
    if "solucoes" not in out:
        raise SystemExit("PAGES_MIRROR: sales-public/solucoes.html has no canonical (run the sales build first)")
    return out


def published_html_pages(files: list[str]) -> list[str]:
    """Pages paths (relative to the project base) of every HTML file the source tree publishes today."""
    paths = set()
    for rel in files:
        parts = rel.split("/")
        if not rel.endswith(".html") or parts[0] == STUB_DIR or any(jekyll_skipped(p) for p in parts):
            continue
        if len(parts) > 1 and parts[0] in NO_STUB_TOP:
            continue
        if rel == "index.html":
            paths.add("/")
        elif parts[-1] == "index.html":
            paths.add("/" + "/".join(parts[:-1]) + "/")
        else:
            paths.add("/" + rel)
    return sorted(paths)


def target_for(path: str, canon: dict[str, str]) -> str:
    if path == "/":
        return canon["solucoes"]
    slug = path.strip("/").split("/")[-1]
    if slug.endswith(".html"):
        slug = slug[: -len(".html")]
    if slug in ("index", "404"):
        return canon["solucoes"]
    return canon.get(slug, canon["solucoes"])


STYLE = (":root{color-scheme:light dark;--papel:#eef2f5;--tinta:#0e1a2b;--azul:#1a5a96}"
         "@media (prefers-color-scheme:dark){:root{--papel:#0d1723;--tinta:#eef2f5;--azul:#8fc1ef}}"
         "body{margin:0;background:var(--papel);color:var(--tinta);font:1.0625rem/1.6 Verdana,'DejaVu Sans',Arial,sans-serif}"
         "main{max-width:40rem;margin:0 auto;padding:3rem 16px}"
         "h1{font:700 1.5rem/1.2 Arial,sans-serif;margin:0 0 1rem}"
         "a{color:var(--azul);font-weight:700;overflow-wrap:anywhere;text-underline-offset:.2em}"
         "a:focus-visible{outline:3px solid var(--azul);outline-offset:3px}")


def stub_html(target: str, *, title: str, lead: str) -> str:
    t = html.escape(target, quote=True)
    shown = html.escape(target.replace("https://", ""))
    return ("<!doctype html>\n<html lang=\"pt-BR\"><head><meta charset=\"utf-8\">"
            "<meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">"
            "<meta name=\"robots\" content=\"noindex\">"
            f"<title>{html.escape(title)} | ZEVANORY</title>"
            f"<link rel=\"canonical\" href=\"{t}\">"
            f"<meta http-equiv=\"refresh\" content=\"0; url={t}\">"
            f"<style>{STYLE}</style></head>"
            f"<body><main><h1>{html.escape(title)}</h1><p>{html.escape(lead)}</p>"
            f"<p><a href=\"{t}\">{shown}</a></p></main></body></html>\n")


def front_matter(permalink: str) -> str:
    # layout: null keeps GitHub Pages' default-layout plugin from wrapping the stub in a theme.
    return f"---\npermalink: {permalink}\nlayout: null\n---\n"


def stub_name(path: str) -> str:
    if path == "/":
        return "index.html"
    rel = path.strip("/")
    return (rel[: -len(".html")] if rel.endswith(".html") else rel).replace("/", "__") + ".html"


def render() -> dict[str, str]:
    canon = sales_canonicals()
    tracked = tracked_files()
    files: dict[str, str] = {}
    excludes = top_level_entries(tracked)
    for e in excludes:
        if STUB_DIR.startswith(e):
            # Jekyll's exclude also matches by path PREFIX: such an entry would hide the stubs.
            raise SystemExit(f"PAGES_MIRROR: top-level entry {e!r} is a prefix of {STUB_DIR!r}")
    files["_config.yml"] = (
        HEADER
        + "# GitHub Pages publishes ONLY the redirect stubs in pages-mirror/ (see the script docstring).\n"
        + "# Every other top-level entry is excluded; a new top-level entry must be added here (CI: --check).\n"
        + "exclude:\n" + "".join(f"  - {e}\n" for e in excludes)
    )
    for path in published_html_pages(tracked):
        target = target_for(path, canon)
        if f"{STUB_DIR}/{stub_name(path)}" in files:
            raise SystemExit(f"PAGES_MIRROR: two published paths map to the stub {stub_name(path)}")
        files[f"{STUB_DIR}/{stub_name(path)}"] = front_matter(path) + stub_html(
            target, title="Esta página mudou de endereço",
            lead="Esta cópia não é mantida. A versão oficial e atualizada da ZEVANORY está em:")
    files[f"{STUB_DIR}/404.html"] = front_matter("/404.html") + stub_html(
        CATALOGUE, title="Página não encontrada",
        lead="Este endereço não existe nesta cópia. O site oficial da ZEVANORY está em:")
    files[f"{STUB_DIR}/robots.txt"] = front_matter("/robots.txt") + (
        "# Copia antiga sem conteudo: todas as paginas sao redirecionamentos noindex para o site oficial.\n"
        "User-agent: *\nAllow: /\n")
    return files


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    files = render()
    stub_root = ROOT / STUB_DIR
    existing = {p.relative_to(ROOT).as_posix() for p in stub_root.rglob("*") if p.is_file()} if stub_root.exists() else set()
    stale = sorted(existing - set(files))
    changed = sorted(k for k, v in files.items() if not (ROOT / k).is_file() or (ROOT / k).read_text(encoding="utf-8") != v)
    if args.check:
        if stale or changed:
            for k in changed:
                print(f"::error title=PAGES_MIRROR_STALE::{k} differs from the generator output")
            for k in stale:
                print(f"::error title=PAGES_MIRROR_STALE::{k} is no longer generated")
            print("PAGES_MIRROR=STALE (run: python3 scripts/build_pages_mirror.py)")
            return 1
        print(f"PAGES_MIRROR=PASS stubs={sum(1 for k in files if k.startswith(STUB_DIR + '/') and k.endswith('.html'))}")
        return 0
    for k in stale:
        (ROOT / k).unlink()
    for k, v in files.items():
        (ROOT / k).parent.mkdir(parents=True, exist_ok=True)
        (ROOT / k).write_text(v, encoding="utf-8")
    print(f"PAGES_MIRROR=WRITTEN files={len(files)} changed={len(changed)} removed={len(stale)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
