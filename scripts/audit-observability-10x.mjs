import { readFile, access } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const text = (p) => readFile(new URL(p, root), 'utf8');
const exists = async (p) => { try { await access(new URL(p, root)); return true; } catch { return false; } };
const checks=[]; const add=(name,ok)=>checks.push({name,ok:Boolean(ok)});
const pkg=JSON.parse(await text('package.json'));
const release=await text('src/release.mjs');
const health=await text('api/health.mjs');
const status=await text('api/status.mjs');
const probe=await text('scripts/operational-probe.mjs');
add('01 observability core exists',await exists('src/observability.mjs'));
add('02 liveness endpoint exists',await exists('api/live.mjs'));
add('03 liveness in release',release.includes("'/api/live'"));
add('04 health request correlation',health.includes('attachRequestContext'));
add('05 status request correlation',status.includes('attachRequestContext'));
add('06 structured operational logging',health.includes('operationalLog')&&status.includes('operationalLog'));
add('07 production probe exists',await exists('scripts/operational-probe.mjs'));
add('08 probe timeout fail closed',probe.includes('AbortController')&&probe.includes('process.exit(1)'));
add('09 probe checks live health release status',['/api/live','/api/health','/api/release','/api/status'].every((p)=>probe.includes(p)));
add('10 npm probe command',pkg.scripts?.['probe:production']==='node scripts/operational-probe.mjs');
for(const c of checks) console.log(`${c.ok?'APPROVED':'FAILED'} ${c.name}`);
const failed=checks.filter((c)=>!c.ok);
console.log(`AUDIT_OBSERVABILITY_10X_${failed.length?'BLOCKED':'APPROVED'} units=${checks.length} approved=${checks.length-failed.length} failed=${failed.length}`);
if(failed.length) process.exit(1);
