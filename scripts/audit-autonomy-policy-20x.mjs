import {readFile} from 'node:fs/promises';
import {AUTONOMY_POLICY} from '../src/autonomyPolicy.mjs';
const root=new URL('../',import.meta.url);const text=(p)=>readFile(new URL(p,root),'utf8');const checks=[];const add=(name,ok)=>checks.push({name,ok:Boolean(ok)});
const policy=await text('src/autonomyPolicy.mjs');const control=await text('src/agentControl.mjs');const worker=await text('src/agentWorker.mjs');const env=await text('.env.example');const evidence=await text('evidence/EG-0059-progressive-autonomy-policy.md');
add('01 autonomy policy versioned',AUTONOMY_POLICY.version==='progressive-autonomy-v1');
add('02 guarded default',env.includes('AGENT_AUTONOMY_MODE=guarded'));
add('03 approval flag alone cannot bypass',!control.includes("AGENT_HUMAN_APPROVAL_REQUIRED==='false'"));
add('04 progressive mode explicit',policy.includes("mode!=='progressive'"));
add('05 human approval policy explicit',policy.includes('human_approval_policy_enabled'));
add('06 commercial gates required',policy.includes('commercial_gates_closed'));
add('07 eval score threshold',policy.includes("num(evalResult.score)<0.95"));
add('08 learning confidence threshold',AUTONOMY_POLICY.min_learning_confidence>=.70);
add('09 learning sample threshold',AUTONOMY_POLICY.min_learning_matured>=60);
add('10 learned channel coherence',policy.includes('learning_channel_mismatch'));
add('11 runtime sample threshold',AUTONOMY_POLICY.min_runs_24h>=50);
add('12 eval coverage threshold',AUTONOMY_POLICY.min_eval_coverage>=.99);
add('13 eval pass threshold',AUTONOMY_POLICY.min_eval_pass_rate>=.99);
add('14 failed run cap',AUTONOMY_POLICY.max_failed_run_ratio<=.01);
add('15 retry must be zero',AUTONOMY_POLICY.max_retry_24h===0);
add('16 dead letter must be zero',AUTONOMY_POLICY.max_dead_letters_24h===0);
add('17 refund never autonomous',AUTONOMY_POLICY.never_autonomous.includes('refund_payment'));
add('18 checkout financial preconditions',policy.includes('financial_preconditions_closed'));
add('19 worker records autonomy reason',worker.includes('autonomy_reason'));
add('20 evidence says not activated',evidence.includes('nao a ativa em producao')||evidence.includes('não a ativa em produção'));
for(const c of checks)console.log(`${c.ok?'APPROVED':'FAILED'} ${c.name}`);const failed=checks.filter(c=>!c.ok);console.log(`AUDIT_AUTONOMY_POLICY_20X_${failed.length?'BLOCKED':'APPROVED'} units=20 approved=${20-failed.length} failed=${failed.length}`);if(failed.length)process.exit(1);
