import { readFile, access } from 'node:fs/promises';
import { certifyLifecycleEvidence, LIFECYCLE_PROOF_POLICY } from '../src/lifecycleCertificationEngine.mjs';
import { SALES_LIFECYCLE_CANONICAL_V2 } from '../src/salesLifecycleV2.mjs';
import { REQUIRED_TABLES, REQUIRED_MIGRATIONS } from '../src/schemaHealth.mjs';
const root=new URL('../',import.meta.url); const checks=[];
const text=p=>readFile(new URL(p,root),'utf8');
const exists=async p=>{try{await access(new URL(p,root));return true}catch{return false}};
const add=(name,ok)=>checks.push({name,ok:Boolean(ok)});
const empty=certifyLifecycleEvidence({});
add('01 canonical dimensions remain 39',SALES_LIFECYCLE_CANONICAL_V2.length===39);
add('02 every dimension has proof policy',SALES_LIFECYCLE_CANONICAL_V2.every(k=>typeof LIFECYCLE_PROOF_POLICY[k]==='function'));
add('03 technical readiness alone caps at 9',empty.proven_dimensions===0&&empty.dimensions.every(x=>x.score===9));
add('04 production evidence table required',REQUIRED_TABLES.includes('lifecycle_evidence_events'));
add('05 migration 013 required',REQUIRED_MIGRATIONS.includes('013_lifecycle_evidence_certification'));
add('06 migration file exists',await exists('db/migrations/013_lifecycle_evidence_certification.sql'));
add('07 lifecycle certification view exists',(await text('api/config.mjs')).includes("view')==='lifecycle'"));
add('08 evidence snapshot permanently non-unlocking',(await text('src/lifecycleEvidenceSnapshot.mjs')).includes('commercial_unlock:false'));
add('09 direct proof needs three observed events',(await text('src/lifecycleCertificationEngine.mjs')).includes('>=3'));
add('10 sales static gate remains fail closed',(await text('src/salesLifecycleV2.mjs')).includes('audit_10x_pass:false'));
for(const c of checks) console.log(`${c.ok?'APPROVED':'FAILED'} ${c.name}`);
const failed=checks.filter(x=>!x.ok); console.log(`AUDIT_LIFECYCLE_EVIDENCE_10X_${failed.length?'BLOCKED':'APPROVED'} units=10 approved=${10-failed.length} failed=${failed.length}`); if(failed.length) process.exit(1);
