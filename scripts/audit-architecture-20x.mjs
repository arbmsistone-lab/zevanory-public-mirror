import { readFile, access } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
const root=new URL('../',import.meta.url); const checks=[];
const text=(p)=>readFile(new URL(p,root),'utf8');
const exists=async(p)=>{try{await access(new URL(p,root));return true}catch{return false}};
const add=(name,ok)=>checks.push({name,ok:Boolean(ok)});
const run=(cmd,args)=>spawnSync(cmd,args,{cwd:root,encoding:'utf8',shell:false}).status===0;
const runShell=(cmd)=>spawnSync(cmd,{cwd:root,encoding:'utf8',shell:true}).status===0;
const env=await text('.env.example'); const vercel=JSON.parse(await text('vercel.json')); const checkout=await text('api/checkout/asaas.mjs'); const webhook=await text('api/webhooks/asaas.mjs'); const status=await text('api/status.mjs');
const headers=Object.fromEntries(vercel.headers[0].headers.map(x=>[x.key,x.value]));
add('01 sales global switch off',env.includes('SALE_GLOBALLY_ENABLED=false'));
add('02 pre-sale switch off',env.includes('PRE_SALE_GATES_APPROVED=false'));
add('03 checkout switch off',env.includes('CHECKOUT_ENABLED=false'));
add('04 WhatsApp switch off',env.includes('WHATSAPP_SALES_ENABLED=false'));
add('05 financial switch off',env.includes('FINANCIAL_EVENTS_ENABLED=false'));
add('06 strict CSP',headers['Content-Security-Policy']?.includes("script-src 'self'")&&!headers['Content-Security-Policy']?.includes('unsafe-inline'));
add('07 clickjacking blocked',headers['X-Frame-Options']==='DENY');
add('08 nosniff enabled',headers['X-Content-Type-Options']==='nosniff');
add('09 origin isolation enabled',headers['Cross-Origin-Opener-Policy']==='same-origin'&&headers['Cross-Origin-Resource-Policy']==='same-origin');
add('10 checkout fail closed',checkout.includes('sales_globally_blocked')&&checkout.includes('checkout_environment_invalid'));
add('11 webhook remains provider-truth based',webhook.includes('fetchAsaasPayment')&&webhook.includes('payment_reconciliation_failed'));
add('12 status endpoint exposes aggregates only',!status.includes('select *')&&!status.includes('contact_ref')&&!status.includes('session_id'));
add('13 schema remains no-inventory 9x7',(await text('src/schemaHealth.mjs')).includes("'affiliate_commissions'")&&(await text('src/schemaHealth.mjs')).includes("'service_fulfillment'"));
add('14 DR script exists',await exists('scripts/dr-rehearsal.mjs'));
add('15 DR rollback enforced',(await text('scripts/dr-rehearsal.mjs')).includes("client.query('ROLLBACK')"));
add('16 release stays globally blocked',(await text('src/release.mjs')).includes("salesMode: 'globally-blocked'"));
add('17 dependency audit clean',runShell('npm audit --omit=dev --audit-level=high'));
add('18 security audit 10x',run(process.execPath,['scripts/audit-security-10x.mjs']));
add('19 observability audit 10x',run(process.execPath,['scripts/audit-observability-10x.mjs']));
add('20 resilience smoke',run(process.execPath,['scripts/resilience-smoke.mjs']));
for(const c of checks) console.log(`${c.ok?'APPROVED':'FAILED'} ${c.name}`);
const failed=checks.filter(c=>!c.ok); console.log(`AUDIT_ARCHITECTURE_20X_${failed.length?'BLOCKED':'APPROVED'} units=20 approved=${20-failed.length} failed=${failed.length}`);
if(failed.length) process.exit(1);
