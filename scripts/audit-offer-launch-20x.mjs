import { readFile, access } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { ARBM_SIST_OFFER } from '../src/offerCatalog.mjs';
import { digitalFulfillmentReadiness } from '../src/digitalFulfillment.mjs';
import { RELEASE } from '../src/release.mjs';
const root=new URL('../',import.meta.url); const checks=[];
const text=async p=>readFile(new URL(p,root),'utf8');
const exists=async p=>{try{await access(new URL(p,root));return true}catch{return false}};
const add=(name,ok)=>checks.push({name,ok:Boolean(ok)});
const run=(...args)=>spawnSync(process.execPath,args,{cwd:root,encoding:'utf8'}).status===0;
const html=await text('public/arbm-sist.html'); const js=await text('public/arbm-sist.js'); const vercel=await text('vercel.json');
add('01 canonical ARBM SIST offer',ARBM_SIST_OFFER.id==='OFFER-0001'&&ARBM_SIST_OFFER.product==='ARBM SIST');
add('02 version and artifact pinned',ARBM_SIST_OFFER.version==='8.1.0'&&/^[A-F0-9]{64}$/.test(ARBM_SIST_OFFER.artifact_sha256));
add('03 digital product no inventory',ARBM_SIST_OFFER.offer_type==='digital_product'&&ARBM_SIST_OFFER.inventory_required===false);
add('04 pilot price explicit',ARBM_SIST_OFFER.price_brl===497&&ARBM_SIST_OFFER.price_status==='pilot_hypothesis_not_validated');
add('05 offer landing exists',await exists('public/arbm-sist.html')&&await exists('public/arbm-sist.css')&&await exists('public/arbm-sist.js'));
add('06 landing route published',vercel.includes('/arbm-sist')&&RELEASE.requiredRoutes.includes('/arbm-sist'));
add('07 no invented results',html.includes('SEM PROMESSA DE RESULTADO INVENTADO'));
add('08 tracking by source',js.includes("utm_source")&&js.includes("cta_whatsapp")&&js.includes("page_view"));
add('09 prelaunch and active states',js.includes('PRÉ-LANÇAMENTO')&&js.includes('OFERTA ATIVA'));
add('10 support separated from sales gate',js.includes('support_whatsapp_number')&&js.includes('config.whatsapp_enabled'));
const blocked=digitalFulfillmentReadiness({order_status:'created',payment_confirmed:false});
add('11 delivery blocked before payment',blocked.ready===false&&blocked.blockers.includes('payment_not_reconciled'));
add('12 no public artifact download',blocked.public_download===false&&html.includes('Executáveis não assinados não fazem parte'));
add('13 secure fulfillment reference required',blocked.blockers.includes('secure_artifact_not_configured'));
add('14 primary channel plan',ARBM_SIST_OFFER.primary_channels.join(',')==='youtube,instagram,whatsapp,zevanory');
add('15 channel plan documented',await exists('launch/ARBM-SIST-CHANNEL-PLAN.md'));
add('16 content queue documented',await exists('launch/ARBM-SIST-CONTENT-QUEUE.md'));
add('17 offer tests pass',run('--test','test/arbm-sist-offer.test.mjs'));
add('18 config API exposes offer metadata',(await text('api/config.mjs')).includes('publicOffer()'));
add('19 release remains sales blocked',RELEASE.salesMode==='globally-blocked'&&RELEASE.checkoutMode==='globally-blocked');
add('20 EG0039 release',RELEASE.id==='ZEVANORY-EG0039-FINAL'&&RELEASE.assurance.offer_launch_20x==='approved');
for(const c of checks) console.log(`${c.ok?'APPROVED':'FAILED'} ${c.name}`);
const failed=checks.filter(x=>!x.ok); console.log(`AUDIT_OFFER_LAUNCH_20X_${failed.length?'BLOCKED':'APPROVED'} units=20 approved=${20-failed.length} failed=${failed.length}`); if(failed.length)process.exit(1);
